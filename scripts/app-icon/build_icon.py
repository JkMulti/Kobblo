"""Writes Kobblo's launcher icon from design.py.

    python3 scripts/app-icon/build_icon.py                    the three adaptive-icon layers
    python3 scripts/app-icon/build_icon.py --images           also the legacy mipmaps and the Play Store image
    python3 scripts/app-icon/build_icon.py --preview out.html a sheet of launcher shapes and themed icons

--images renders with Google Chrome and encodes with cwebp (brew install webp). The legacy mipmaps are
only a fallback: with minSdk 26 every launcher reads the adaptive icon.
"""
import os
import subprocess
import sys
import tempfile

import design

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RES = os.path.join(ROOT, "app", "src", "main", "res")
CHROME = os.environ.get("CHROME", "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome")
HEADER = "Generated by scripts/app-icon/build_icon.py; change design.py and run it again."


def write_layers():
    files = {
        "ic_launcher_background.xml": (design.background(), f"{HEADER} A white tile, cooling to the palest blue at its foot."),
        "ic_launcher_foreground.xml": (design.foreground(), f"{HEADER} Browse's folder with blue hills and a white sun along its foot."),
        "ic_launcher_monochrome.xml": (design.monochrome(), f"{HEADER} The themed icon: the folder in one color, the sky parted from the hills and the sun cut out."),
    }
    for name, (layers, comment) in files.items():
        with open(os.path.join(RES, "drawable", name), "w") as f:
            f.write(design.vector_xml(layers, comment))
        print("wrote", name)


def render(svg_text, size, out_png):
    with tempfile.NamedTemporaryFile("w", suffix=".svg", delete=False) as f:
        f.write(svg_text)
    subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars",
                    "--default-background-color=00000000", f"--window-size={size},{size}",
                    f"--screenshot={out_png}", "file://" + f.name],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    os.unlink(f.name)


def write_images():
    layers = design.background() + design.foreground()
    # A legacy icon's shape is 44 of its 48dp, so the 72 a launcher shows gets a margin of 72 * 2/44.
    pad = 72 * 2 / 44
    legacy_view = (18 - pad, 18 - pad, 72 + 2 * pad, 72 + 2 * pad)
    with tempfile.TemporaryDirectory() as tmp:
        for density, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
            for name, mask in (("ic_launcher", "squircle"), ("ic_launcher_round", "circle")):
                png = os.path.join(tmp, f"{name}-{density}.png")
                render(design.svg(layers, "i", mask, px, legacy_view), px, png)
                out = os.path.join(RES, f"mipmap-{density}", f"{name}.webp")
                subprocess.run(["cwebp", "-quiet", "-lossless", "-exact", png, "-o", out], check=True)
                print("wrote", os.path.relpath(out, ROOT))
        # Google Play takes a full square and rounds it itself.
        store = os.path.join(ROOT, "app", "src", "main", "ic_launcher-playstore.png")
        render(design.svg(layers, "p", None, 512), 512, store)
        print("wrote", os.path.relpath(store, ROOT))


def write_preview(path):
    layers = design.background() + design.foreground()

    def themed(tile, ink):
        return [dict(d="M0 0H108V108H0Z", fill=tile)] + [dict(layer, fill=ink) for layer in design.monochrome()]

    light, dark = themed("#D3E3FD", "#0842A0"), themed("#1F1F1F", "#A8C7FA")
    big = "".join(design.svg(layers, f"b{m}", m, 240) for m in design.MASKS)
    big += design.svg(light, "tl", "circle", 240) + design.svg(dark, "td", "circle", 240)
    small = "".join(design.svg(layers, f"s{m}", m, 60) for m in design.MASKS)
    small += design.svg(light, "stl", "circle", 60) + design.svg(dark, "std", "circle", 60)
    with open(path, "w") as f:
        f.write('<!doctype html><html><body style="margin:0;padding:16px;background:#ececf0">'
                f'<div style="display:flex;gap:16px">{big}</div>'
                '<div style="display:flex;gap:22px;margin-top:16px;padding:22px;border-radius:14px;width:fit-content;'
                f'background:linear-gradient(135deg,#355c7d,#6c5b7b 50%,#c06c84)">{small}</div></body></html>')
    print("wrote", path)


if __name__ == "__main__":
    args = sys.argv[1:]
    write_layers()
    if "--images" in args:
        write_images()
    if "--preview" in args:
        write_preview(args[args.index("--preview") + 1])
